// Rewrites src/lib/product-images.ts (static imports, so next/image gets dimensions + blur placeholders) to match
// src/lib/catalog.json: a main photo per product (src/assets/products/<slug>.webp) plus any extra views that exist —
// <slug>-back.webp and <slug>-side.webp. No API key needed.
// Usage: node scripts/sync-product-images.mjs (generate-products.mjs and import-krea-products.mjs also run it).
import { readFile, writeFile, access } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "src/assets/products");
const exists = (p) => access(p).then(() => true, () => false);
// only products whose main photo exists — new pieces appear in the shop as soon as their front shot lands
const all = JSON.parse(await readFile(path.join(ROOT, "src/lib/catalog.json"), "utf8"));
const catalog = [];
for (const p of all) if (await exists(path.join(OUT, `${p.slug}.webp`))) catalog.push(p);
const id = (s) => s.replace(/-([a-z])/g, (_, x) => x.toUpperCase());
const VIEWS = ["back", "side"];

const extra = []; // [slug, view]
for (const p of catalog) for (const v of VIEWS) if (await exists(path.join(OUT, `${p.slug}-${v}.webp`))) extra.push([p.slug, v]);
const cap = (s) => s[0].toUpperCase() + s.slice(1);

await writeFile(
  path.join(ROOT, "src/lib/product-images.ts"),
  "// Static imports so next/image gets dimensions + blur placeholders. One per catalog.json entry, plus extra views.\n" +
    "// Generated by scripts/sync-product-images.mjs — don't edit by hand.\n" +
    'import type { StaticImageData } from "next/image";\n' +
    catalog.map((p) => `import ${id(p.slug)} from "@/assets/products/${p.slug}.webp";`).join("\n") +
    "\n" +
    extra.map(([s, v]) => `import ${id(s)}${cap(v)} from "@/assets/products/${s}-${v}.webp";`).join("\n") +
    "\n\nexport const productImages = {\n" +
    catalog.map((p) => `  "${p.slug}": ${id(p.slug)},`).join("\n") +
    "\n};\n\n" +
    "export type ProductView = \"back\" | \"side\";\n" +
    "export const productViews: Partial<Record<keyof typeof productImages, Partial<Record<ProductView, StaticImageData>>>> = {\n" +
    catalog
      .filter((p) => extra.some(([s]) => s === p.slug))
      .map((p) => `  "${p.slug}": { ${extra.filter(([s]) => s === p.slug).map(([s, v]) => `${v}: ${id(s)}${cap(v)}`).join(", ")} },`)
      .join("\n") +
    "\n};\n",
);
console.log(`product-images.ts: ${catalog.length}/${all.length} products photographed, ${extra.length} extra views`);
